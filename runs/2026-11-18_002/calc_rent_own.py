"""賃貸 vs 持ち家 35年の仮の試算。すべて仮置き(実在の物件ではない)。
共通: 物件4,000万円(マンション70㎡想定)、頭金400万円(自己資金。賃貸の人は同額を手元に残す)、35年、元利均等。
持ち家の毎年の費用: 固定資産税+都市計画税=評価額(価格の60%と仮)×(1.4%+0.3%)、修繕積立金=335円/㎡×70㎡/月(国交省ガイドライン令和6年6月改定の、20階未満・延床5,000㎡未満の平均の目安)。管理費・火災保険・ローン手数料・登録免許税等は含めない(持ち家に有利な抜けも不利な抜けもある)。住宅ローン控除・投資の利回り・物価・金利の変動は含めない。
"""
P=4000; down=400; L=P-down; years=35; n=years*12
def pay(r):
    i=r/12
    return L*10000*i/(1-(1+i)**-n) if r else L*10000/n
tax=P*0.6*(0.014+0.003)*10000/12      # 円/月
rep=335*70                              # 円/月
def diff(r,sale,rent):
    """持ち家-賃貸の、35年後の手元のお金の差(円)。プラスなら持ち家が残る。頭金400万は持ち家では物件に使い、賃貸では手元に残る。"""
    m=pay(r); own_cost=(m+tax+rep)*n
    return sale*P*10000 - down*10000 - own_cost + rent*n
if __name__=="__main__":
  for rent in (80000,100000,120000,150000):
    print(f"--- 家賃 月{rent:,}円")
    for r in (0.01,0.02,0.03):
      row=[f"売値{int(sa*100)}%:{diff(r,sa,rent)/1e4:,.0f}万" for sa in (0.3,0.5,0.7)]
      print(f"金利{r*100:.0f}% 月返済{pay(r):,.0f} 税{tax:,.0f} 修繕{rep:,} | "+" / ".join(row))
  print("--- 並ぶ家賃(持ち家=賃貸になる月の家賃)")
  for r in (0.01,0.02,0.03):
    out=[]
    for sa in (0.3,0.5,0.7):
        m=pay(r); own_cost=(m+tax+rep)*n
        need=(own_cost+down*10000-sa*P*10000)/n   # diff=0 → rent
        out.append(f"売値{int(sa*100)}%:{need:,.0f}円")
    print(f"金利{r*100:.0f}%: "+" / ".join(out))

  print("--- 持ち家の月の合計(返済+税+修繕)と、35年で戻らないお金(利息+税+修繕積立金。頭金・元本は除く)")
  for r in (0.01,0.02,0.03):
    m=pay(r); interest=m*n-L*10000
    print(f"金利{r*100:.0f}%: 月の合計{m+tax+rep:,.0f}円 / 利息{interest/1e4:,.0f}万 税{tax*n/1e4:,.0f}万 修繕積立金{rep*n/1e4:,.0f}万 合計{(interest+tax*n+rep*n)/1e4:,.0f}万")
